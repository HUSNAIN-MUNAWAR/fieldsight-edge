"""Run the real local API edge queue and render its measured state trace."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import sys
import tempfile
from pathlib import Path

import cv2
import numpy as np
from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parents[1]
API_ROOT = ROOT / "apps" / "api"
sys.path.insert(0, str(API_ROOT))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def render_trace(events: list[dict], output: Path) -> tuple[int, int, float, int]:
    width, height, fps = 1280, 720, 2.0
    writer = cv2.VideoWriter(
        str(output), cv2.VideoWriter_fourcc(*"mp4v"), fps, (width, height)
    )
    if not writer.isOpened():
        raise RuntimeError(f"Could not open video writer for {output}")
    for event in events:
        frame = np.full((height, width, 3), (18, 24, 38), dtype=np.uint8)
        state = event.get("state", "unknown")
        color = (
            (70, 210, 125)
            if state in {"Synchronized", "online"}
            else (230, 185, 75)
            if state in {"Queued offline", "syncing"}
            else (70, 120, 235)
        )
        cv2.putText(
            frame,
            "FIELDSIGHT EDGE | OFFLINE-TO-SYNC TRACE",
            (52, 70),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.98,
            (230, 236, 248),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"step {event['sequence']} / {len(events)}",
            (53, 112),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.72,
            (150, 170, 198),
            2,
            cv2.LINE_AA,
        )
        cv2.rectangle(frame, (52, 165), (1228, 335), (35, 46, 68), -1)
        cv2.putText(
            frame,
            f"action: {event['action']}",
            (80, 220),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.92,
            (240, 244, 250),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"device: {event['device']}  |  state: {state}",
            (80, 275),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.78,
            color,
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"HTTP {event['status_code']}  |  media: {event.get('media_id') or '-'}",
            (80, 320),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.68,
            (180, 190, 205),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"queued jobs: {event.get('queued_jobs', '-')}",
            (90, 445),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.88,
            (140, 210, 180),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"synchronized: {event.get('synchronized_jobs', '-')}",
            (90, 500),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.88,
            (140, 210, 180),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            f"findings created: {event.get('findings_created', '-')}",
            (90, 555),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.88,
            (140, 210, 180),
            2,
            cv2.LINE_AA,
        )
        cv2.putText(
            frame,
            "All records are generated by the local deterministic demo path.",
            (90, 640),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.66,
            (190, 200, 215),
            2,
            cv2.LINE_AA,
        )
        writer.write(frame)
    writer.release()
    return width, height, fps, len(events)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output-dir", type=Path, default=ROOT / "docs/runtime_evidence"
    )
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="fieldsight-runtime-") as temp_dir:
        os.environ["FIELDSIGHT_ENV"] = "development"
        os.environ["FIELDSIGHT_DEMO_MODE"] = "true"
        os.environ["DATABASE_URL"] = (
            f"sqlite:///{Path(temp_dir) / 'fieldsight-runtime.db'}"
        )
        os.environ["FIELDSIGHT_WORKER_MODE"] = "inline"
        sys.path.insert(0, str(API_ROOT))
        from app.main import app
        from app.database import engine

        events: list[dict] = []
        with TestClient(app) as client:
            login = client.post(
                "/api/auth/login",
                json={"email": "admin@fieldsight.demo", "password": "DemoPass123!"},
            )
            login.raise_for_status()
            token = login.json()["access_token"]
            headers = {"Authorization": f"Bearer {token}"}

            mode = client.post(
                "/api/v1/devices/edge-03/mode",
                headers=headers,
                json={"mode": "offline"},
            )
            mode.raise_for_status()
            events.append(
                {
                    "sequence": 1,
                    "action": "set offline",
                    "device": "edge-03",
                    "state": mode.json()["state"],
                    "status_code": mode.status_code,
                }
            )

            for sequence in range(2, 5):
                capture = client.post(
                    "/api/v1/devices/edge-03/capture", headers=headers
                )
                capture.raise_for_status()
                payload = capture.json()
                events.append(
                    {
                        "sequence": sequence,
                        "action": "capture while offline",
                        "device": "edge-03",
                        "state": payload["sync_job"]["state"],
                        "status_code": capture.status_code,
                        "media_id": payload["media"]["id"],
                        "queued_jobs": payload["sync_job"]["state"],
                    }
                )

            before = client.get("/api/v1/devices/edge-03", headers=headers)
            before.raise_for_status()
            events.append(
                {
                    "sequence": 5,
                    "action": "inspect offline queue",
                    "device": "edge-03",
                    "state": before.json()["state"],
                    "status_code": before.status_code,
                    "queued_jobs": len(before.json()["sync_jobs"]),
                }
            )

            sync = client.post("/api/v1/devices/edge-03/sync", headers=headers)
            sync.raise_for_status()
            sync_payload = sync.json()
            events.append(
                {
                    "sequence": 6,
                    "action": "synchronize",
                    "device": "edge-03",
                    "state": sync_payload["device"]["state"],
                    "status_code": sync.status_code,
                    "synchronized_jobs": sync_payload["synchronized_jobs"],
                    "findings_created": len(sync_payload["findings"]),
                }
            )

            report = client.get("/api/reports/export.pdf", headers=headers)
            report.raise_for_status()
            report_path = args.output_dir / "fieldsight-runtime-report.pdf"
            report_path.write_bytes(report.content)
            events.append(
                {
                    "sequence": 7,
                    "action": "export report",
                    "device": "edge-03",
                    "state": "report generated",
                    "status_code": report.status_code,
                    "report_bytes": len(report.content),
                }
            )

        engine.dispose()
        trace_json = args.output_dir / "edge-runtime-trace.json"
        trace_json.write_text(json.dumps(events, indent=2) + "\n", encoding="utf-8")
        trace_csv = args.output_dir / "edge-runtime-trace.csv"
        with trace_csv.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(
                handle, fieldnames=sorted({key for event in events for key in event})
            )
            writer.writeheader()
            writer.writerows(events)
        video = args.output_dir / "edge-runtime-trace.mp4"
        width, height, fps, frames = render_trace(events, video)
        capture = cv2.VideoCapture(str(video))
        decoded_frames = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
        ok, poster = capture.read()
        capture.release()
        if not ok:
            raise RuntimeError("Could not decode the first evidence frame")
        poster_path = args.output_dir / "edge-runtime-trace-poster.jpg"
        cv2.imwrite(str(poster_path), poster)

    summary = {
        "status": "completed",
        "workflow": "login -> offline mode -> 3 captures -> queue inspection -> sync -> PDF report",
        "device": "edge-03",
        "captures_queued": 3,
        "synchronized_jobs": next(
            event.get("synchronized_jobs", 0)
            for event in events
            if event["action"] == "synchronize"
        ),
        "findings_created": next(
            event.get("findings_created", 0)
            for event in events
            if event["action"] == "synchronize"
        ),
        "all_http_statuses": sorted({event["status_code"] for event in events}),
        "video": {
            "width": width,
            "height": height,
            "fps": fps,
            "rendered_frames": frames,
            "decoded_frames": decoded_frames,
        },
        "claim_boundary": "This is a local SQLite deterministic demo with synthetic captures and deterministic inference; it does not claim physical camera accuracy or a deployed edge model.",
        "artifacts": {
            path.name: {"bytes": path.stat().st_size, "sha256": sha256(path)}
            for path in (trace_json, trace_csv, video, poster_path, report_path)
        },
    }
    (args.output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
